package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"io"
	"path/filepath"
	"strings"

	"github.com/d7z-team/mini-go/compiler/bootstrap/compilerentry"
	"github.com/d7z-team/mini-go/compiler/source"
	"github.com/d7z-team/mini-go/compiler/workspace"
	"github.com/d7z-team/mini-go/stdlib"
)

func runCompilerCore(args []string, stderr io.Writer) error {
	flags := flag.NewFlagSet("mini-go-dev compiler-core", flag.ContinueOnError)
	flags.SetOutput(stderr)
	output := flags.String("out", "", "generated Go source")
	if err := flags.Parse(args); err != nil {
		return err
	}
	if flags.NArg() != 0 || strings.TrimSpace(*output) == "" {
		return errors.New("compiler-core requires -out")
	}
	library := stdlib.Open()
	sources, err := workspace.StandardLibrary(library)
	if err != nil {
		return err
	}
	paths, err := sources.PackagePaths()
	if err != nil {
		return err
	}
	sourceFiles := make(map[string]source.File)
	packages := make([]compilerentry.Package, 0, len(paths))
	for _, modulePath := range paths {
		pkg, found, err := sources.Package(modulePath)
		if err != nil {
			return err
		}
		if !found {
			return fmt.Errorf("stdlib package %q disappeared during generation", modulePath)
		}
		embedded := compilerentry.Package{
			Namespace: pkg.ID.Namespace, PackagePath: pkg.ID.Path, ModulePath: pkg.ModulePath,
			Files: make([]compilerentry.File, len(pkg.Files)),
		}
		for _, file := range pkg.Files {
			sourceFiles[file.Path] = file
		}
		for i, file := range pkg.Files {
			embedded.Files[i] = compilerentry.File{Path: file.Path, Text: file.Text}
		}
		for _, resource := range pkg.Resources {
			if strings.HasSuffix(resource.Path, "_test.mgo") {
				continue
			}
			value := compilerentry.Resource{Path: resource.Path, Data: append([]byte(nil), resource.Data...)}
			file, exists := sourceFiles[pkg.ModulePath+"/"+resource.Path]
			if !exists {
				file, exists = sourceFiles[resource.Path]
			}
			if exists && bytes.Equal(resource.Data, []byte(file.Text)) {
				value.SourcePath = file.Path
				value.Data = nil
			}
			embedded.Resources = append(embedded.Resources, value)
		}
		packages = append(packages, embedded)
	}
	bundle, err := compilerentry.EncodeCoreBundle(packages)
	if err != nil {
		return fmt.Errorf("encode compiler core: %w", err)
	}
	bundlePath := strings.TrimSuffix(*output, filepath.Ext(*output)) + ".bundle"
	if err := writeGeneratedFile(bundlePath, bundle); err != nil {
		return err
	}
	generated := "// Code generated by mini-go compiler-core; DO NOT EDIT.\n\n" +
		"package compilerentry\n\n" +
		"import _ \"embed\"\n\n" +
		"//go:embed " + filepath.Base(bundlePath) + "\n" +
		"var embeddedCoreBundle []byte\n\n" +
		"var embeddedCorePackages = mustDecodeCoreBundle(embeddedCoreBundle)\n"
	formatted, err := format.Source([]byte(generated))
	if err != nil {
		return fmt.Errorf("format generated compiler core loader: %w", err)
	}
	return writeGeneratedFile(*output, formatted)
}
