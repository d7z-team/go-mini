package main

import (
	"encoding/json"
	"errors"
	"flag"
	"go/ast"
	"go/parser"
	"go/token"
	"io"
	"sort"
	"strconv"
	"strings"
)

func runVSCodeGrammar(args []string, stderr io.Writer) error {
	flags := flag.NewFlagSet("mini-go-dev vscode-grammar", flag.ContinueOnError)
	flags.SetOutput(stderr)
	output := flags.String("out", "", "generated TextMate grammar")
	if err := flags.Parse(args); err != nil {
		return err
	}
	if *output == "" || flags.NArg() != 0 {
		return errors.New("vscode-grammar requires -out")
	}
	repository := map[string]any{}
	for _, input := range []struct{ path, declaration, category, scope string }{
		{"compiler/token/token.go", "keywords", "keywords", "keyword.control.mgo"},
		{"compiler/semantic/builtins.go", "predeclaredBuiltinNames", "builtins", "support.function.builtin.mgo"},
		{"compiler/semantic/types.go", "canonicalSourceTypeName", "types", "storage.type.mgo"},
	} {
		file, err := parser.ParseFile(token.NewFileSet(), input.path, nil, 0)
		if err != nil {
			return err
		}
		var names []string
		for _, declaration := range file.Decls {
			var node ast.Node
			switch declaration := declaration.(type) {
			case *ast.FuncDecl:
				if declaration.Name.Name == input.declaration {
					node = declaration.Body
				}
			case *ast.GenDecl:
				for _, spec := range declaration.Specs {
					if value, ok := spec.(*ast.ValueSpec); ok && len(value.Names) == 1 && value.Names[0].Name == input.declaration && len(value.Values) == 1 {
						node = value.Values[0]
					}
				}
			}
			if node == nil {
				continue
			}
			ast.Inspect(node, func(node ast.Node) bool {
				var literals []ast.Expr
				switch value := node.(type) {
				case *ast.CaseClause:
					literals = value.List
				case *ast.KeyValueExpr:
					literals = []ast.Expr{value.Key}
				case *ast.CompositeLit:
					if input.category == "builtins" {
						literals = value.Elts
					}
				}
				for _, value := range literals {
					if literal, ok := value.(*ast.BasicLit); ok && literal.Kind == token.STRING {
						name, err := strconv.Unquote(literal.Value)
						if err == nil {
							names = append(names, name)
						}
					}
				}
				return true
			})
		}
		if len(names) == 0 {
			return errors.New("no language facts for " + input.declaration)
		}
		sort.Strings(names)
		repository[input.category] = map[string]any{"patterns": []any{map[string]string{"name": input.scope, "match": `\b(?:` + strings.Join(names, "|") + `)\b`}}}
	}
	repository["comments"] = map[string]any{"patterns": []any{
		map[string]string{"name": "comment.line.double-slash.mgo", "match": "//.*"},
		map[string]string{"name": "comment.block.mgo", "begin": `/\*`, "end": `\*/`},
	}}
	repository["strings"] = map[string]any{"patterns": []any{
		map[string]any{"name": "string.quoted.double.mgo", "begin": `"`, "end": `"`, "patterns": []any{map[string]string{"match": `\\.`, "name": "constant.character.escape.mgo"}}},
		map[string]any{"name": "string.quoted.single.mgo", "begin": `'`, "end": `'`, "patterns": []any{map[string]string{"match": `\\.`, "name": "constant.character.escape.mgo"}}},
		map[string]string{"name": "string.quoted.raw.mgo", "begin": "`", "end": "`"},
	}}
	repository["numbers"] = map[string]any{"patterns": []any{map[string]string{"name": "constant.numeric.mgo", "match": `\b(?:0[xX][0-9a-fA-F_]+(?:\.[0-9a-fA-F_]*)?(?:[pP][+-]?[0-9_]+)?|0[bB][01_]+|0[oO][0-7_]+|[0-9][0-9_]*(?:\.[0-9_]*)?(?:[eE][+-]?[0-9_]+)?)(?:i)?\b`}}}
	var patterns []any
	for _, name := range []string{"comments", "strings", "keywords", "builtins", "types", "numbers"} {
		patterns = append(patterns, map[string]string{"include": "#" + name})
	}
	data, err := json.MarshalIndent(map[string]any{"name": "Mini-Go", "scopeName": "source.mgo", "comment": "Code generated by mini-go-dev vscode-grammar; DO NOT EDIT.", "patterns": patterns, "repository": repository}, "", "  ")
	if err != nil {
		return err
	}
	return writeGeneratedFile(*output, append(data, '\n'))
}
