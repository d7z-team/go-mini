// Package mgo generates ordinary Mini-Go source from language-independent MRPC schemas.
package mgo

import (
	"bytes"
	"errors"
	"fmt"
	"sort"
	"strconv"
	"strings"

	"github.com/d7z-team/mini-go/tooling/mrpc"
	"github.com/d7z-team/mini-go/tooling/mrpc/gen"
)

// Options controls the generated Mini-Go package name.
type Options struct {
	Package string
}

// Generate emits ordinary Mini-Go client, server, handler, and codec source.
func Generate(catalog mrpc.Catalog, options Options) ([]byte, error) {
	canonical, err := gen.CanonicalCatalog(catalog)
	if err != nil {
		return nil, fmt.Errorf("generate Mini-Go MRPC: %w", err)
	}
	catalog = canonical
	packageName := strings.TrimSpace(options.Package)
	if packageName == "" {
		packageName = catalog.Options["mgo_package"]
		if index := strings.LastIndex(packageName, "/"); index >= 0 {
			packageName = packageName[index+1:]
		}
		packageName = strings.TrimSpace(packageName)
	}
	if packageName == "" {
		return nil, errors.New("generate Mini-Go MRPC: package is required")
	}
	g := generator{catalog: catalog}
	g.line("// Code generated by mini-go rpc generate; DO NOT EDIT.")
	g.line("")
	g.line("package %s", packageName)
	g.line("")
	g.line("import (")
	if gen.UsesFloatingPoint(catalog) {
		g.line("\t\"math\"")
	}
	g.line("\t__mrpc \"rpc\"")
	aliases := make(map[string]string)
	paths := make(map[string]string)
	for _, file := range catalog.Files {
		for _, imported := range file.Imports {
			dependency, ok := catalog.Dependencies[imported.Path]
			if !ok {
				return nil, fmt.Errorf("generate Mini-Go MRPC: missing imported catalog %q", imported.Path)
			}
			path := strings.TrimSpace(dependency.Options["mgo_package"])
			if path == "" {
				return nil, fmt.Errorf("generate Mini-Go MRPC: import %q has no mgo_package option", imported.Path)
			}
			if previous, ok := aliases[imported.Alias]; ok && previous != path {
				return nil, fmt.Errorf("generate Mini-Go MRPC: import alias %q maps to both %q and %q", imported.Alias, previous, path)
			}
			if previous, ok := paths[path]; ok {
				if previous != imported.Alias {
					return nil, fmt.Errorf("generate Mini-Go MRPC: import %q uses both aliases %q and %q", path, previous, imported.Alias)
				}
				continue
			}
			aliases[imported.Alias] = path
			paths[path] = imported.Alias
			g.line("\t%s %q", imported.Alias, path)
		}
	}
	g.line(")")
	g.line("")
	g.line("const mrpcContractID = %q", catalog.ContractID)
	g.line("")
	for _, file := range catalog.Files {
		for _, enum := range file.Enums {
			g.enum(enum)
		}
		for _, message := range file.Messages {
			g.message(message)
		}
	}
	for _, file := range catalog.Files {
		for _, message := range file.Messages {
			g.messageCodec(message)
		}
	}
	for _, file := range catalog.Files {
		for _, service := range file.Services {
			g.service(service)
		}
		for _, resource := range file.Resources {
			g.resource(resource)
		}
	}
	if g.err != nil {
		return nil, fmt.Errorf("generate Mini-Go MRPC: %w", g.err)
	}
	return g.source.Bytes(), nil
}

type generator struct {
	catalog mrpc.Catalog
	source  bytes.Buffer
	err     error
}

func (g *generator) line(format string, args ...any) {
	if len(args) == 0 {
		g.source.WriteString(format)
	} else {
		fmt.Fprintf(&g.source, format, args...)
	}
	g.source.WriteByte('\n')
}

func (g *generator) doc(doc, indent string) {
	for _, line := range strings.Split(strings.TrimSpace(doc), "\n") {
		if line != "" {
			g.line("%s// %s", indent, line)
		}
	}
}

func exported(name string) string {
	if name == "" {
		return "Value"
	}
	return strings.ToUpper(name[:1]) + name[1:]
}

func (g *generator) enum(item mrpc.Enum) {
	g.doc(item.Doc, "")
	g.line("type %s int32", item.Name)
	g.line("")
	g.line("const (")
	for _, value := range item.Values {
		g.doc(value.Doc, "\t")
		g.line("\t%s %s = %d", value.Name, item.Name, value.Number)
	}
	g.line(")")
	wire := g.catalog.Namespace + "." + item.Name
	g.line("func Encode%s(value %s) __mrpc.Value { return __mrpc.Value{Type: %q, Kind: \"int\", Signed: int64(value)} }", item.Name, item.Name, wire)
	g.line("func Decode%s(value __mrpc.Value) (%s, error) { if value.Type != %q || value.Kind != \"int\" || value.Signed < -2147483648 || value.Signed > 2147483647 { return 0, __mrpc.NewError(\"protocol\", \"invalid enum value\") }; return %s(value.Signed), nil }", item.Name, item.Name, wire, item.Name)
	g.line("")
}

func (g *generator) message(item mrpc.Message) {
	g.doc(item.Doc, "")
	g.line("type %s struct {", item.Name)
	for _, field := range item.Fields {
		g.doc(field.Doc, "\t")
		g.line("\t%s %s", exported(field.Name), mgoType(field.Type))
	}
	g.line("}")
	g.line("")
}

func mgoType(typ mrpc.Type) string {
	switch typ.Kind {
	case mrpc.TypeSlice:
		return "[]" + mgoType(*typ.Elem)
	case mrpc.TypeMap:
		return "map[" + mgoType(*typ.Key) + "]" + mgoType(*typ.Elem)
	case mrpc.TypeOptional:
		return "*" + mgoType(*typ.Elem)
	default:
		if typ.Qualifier != "" {
			return typ.Qualifier + "." + typ.Name
		}
		return typ.Name
	}
}

func (g *generator) messageCodec(item mrpc.Message) {
	fields := append([]mrpc.Field(nil), item.Fields...)
	sort.Slice(fields, func(i, j int) bool { return fields[i].ID < fields[j].ID })
	g.line("func __mrpcEncode%s(value %s) __mrpc.Value {", item.Name, item.Name)
	g.line("\tfields := make([]__mrpc.Field, 0, %d)", len(fields))
	for index, field := range fields {
		g.encodeValue("encoded"+strconv.Itoa(index), "value."+exported(field.Name), field.Type, "\t")
		g.line("\tfields = append(fields, __mrpc.Field{ID: %d, Value: encoded%d})", field.ID, index)
	}
	g.line("\treturn __mrpc.Value{Type: %q, Kind: \"struct\", Fields: fields}", g.catalog.Namespace+"."+item.Name)
	g.line("}")
	g.line("")
	g.line("func __mrpcDecode%s(value __mrpc.Value) (out %s, err error) {", item.Name, item.Name)
	g.line("\tif value.Type != %q || value.Kind != \"struct\" { err = __mrpc.NewError(\"protocol\", \"invalid %s value\"); return }", g.catalog.Namespace+"."+item.Name, item.Name)
	for index := range fields {
		g.line("\tfound%d := false", index)
	}
	g.line("\tfor _, field := range value.Fields {")
	g.line("\t\tswitch field.ID {")
	for index, field := range fields {
		g.line("\t\tcase %d:", field.ID)
		g.line("\t\t\tif found%d { err = __mrpc.NewError(\"protocol\", %q); return }", index, "duplicate "+item.Name+"."+field.Name)
		g.decodeValue("decoded"+strconv.Itoa(index), "field.Value", field.Type, "\t\t\t")
		g.line("\t\t\tout.%s, found%d = decoded%d, true", exported(field.Name), index, index)
	}
	g.line("\t\tdefault: err = __mrpc.NewError(\"protocol\", \"unknown MRPC field ID\"); return")
	g.line("\t\t}")
	g.line("\t}")
	for index, field := range fields {
		g.line("\tif !found%d { err = __mrpc.NewError(\"protocol\", %q); return }", index, "missing "+item.Name+"."+field.Name)
	}
	g.line("\treturn")
	g.line("}")
	g.line("")
	if isExported(item.Name) {
		g.line("// Encode%s converts a message to its RPC wire value.", item.Name)
		g.line("func Encode%s(value %s) __mrpc.Value { return __mrpcEncode%s(value) }", item.Name, item.Name, item.Name)
		g.line("// Decode%s validates and decodes an RPC wire value.", item.Name)
		g.line("func Decode%s(value __mrpc.Value) (%s, error) { return __mrpcDecode%s(value) }", item.Name, item.Name, item.Name)
		g.line("")
	}
}

func (g *generator) encodeValue(name, expression string, typ mrpc.Type, indent string) {
	if g.isResourceType(typ) {
		g.err = fmt.Errorf("resource %s requires a call owner", typ.String())
		return
	}
	typeName := g.wireType(typ)
	switch typ.Kind {
	case mrpc.TypeSlice:
		if typ.Elem.Kind == mrpc.TypeName && typ.Elem.Name == "uint8" && typ.Elem.Qualifier == "" {
			g.line("%s%s := __mrpc.Value{Type: %q, Kind: \"nil\"}", indent, name, typeName)
			g.line("%sif %s != nil { %s.Kind, %s.Bytes = \"bytes\", append([]byte{}, %s...) }", indent, expression, name, name, expression)
			return
		}
		g.line("%s%s := __mrpc.Value{Type: %q, Kind: \"nil\"}", indent, name, typeName)
		g.line("%sif %s != nil {", indent, expression)
		g.line("%s\titems := make([]__mrpc.Value, 0, len(%s))", indent, expression)
		g.line("%s\tfor _, item := range %s {", indent, expression)
		g.encodeValue("encodedItem", "item", *typ.Elem, indent+"\t\t")
		g.line("%s\t\titems = append(items, encodedItem)", indent)
		g.line("%s\t}", indent)
		g.line("%s\t%s.Kind, %s.Values = \"slice\", items", indent, name, name)
		g.line("%s}", indent)
	case mrpc.TypeMap:
		g.line("%s%s := __mrpc.Value{Type: %q, Kind: \"nil\"}", indent, name, typeName)
		g.line("%sif %s != nil {", indent, expression)
		g.line("%s\tentries := make([]__mrpc.MapEntry, 0, len(%s))", indent, expression)
		g.line("%s\tfor key, item := range %s {", indent, expression)
		g.encodeValue("encodedKey", "key", *typ.Key, indent+"\t\t")
		g.encodeValue("encodedItem", "item", *typ.Elem, indent+"\t\t")
		g.line("%s\t\tentries = append(entries, __mrpc.MapEntry{Key: encodedKey, Value: encodedItem})", indent)
		g.line("%s\t}", indent)
		g.line("%s\t%s.Kind, %s.Entries = \"map\", entries", indent, name, name)
		g.line("%s}", indent)
	case mrpc.TypeOptional:
		g.line("%s%s := __mrpc.Value{Type: %q, Kind: \"nil\"}", indent, name, typeName)
		g.line("%sif %s != nil {", indent, expression)
		g.encodeValue("item", "(*"+expression+")", *typ.Elem, indent+"\t")
		g.line("%s\t%s.Kind, %s.Optional = \"optional\", &item", indent, name, name)
		g.line("%s}", indent)
	default:
		g.encodeNamed(name, expression, typ, indent)
	}
}

func (g *generator) encodeNamed(name, expression string, typ mrpc.Type, indent string) {
	typeName := g.wireType(typ)
	if typ.Qualifier != "" {
		g.line("%s%s := %s.Encode%s(%s)", indent, name, typ.Qualifier, typ.Name, expression)
		return
	}
	switch typ.Name {
	case "bool":
		g.line("%s%s := __mrpc.Value{Type: %q, Kind: \"bool\", Bool: %s}", indent, name, typeName, expression)
	case "string":
		g.line("%s%s := __mrpc.Value{Type: %q, Kind: \"string\", Text: %s}", indent, name, typeName, expression)
	case "float32":
		g.line("%s%s := __mrpc.Value{Type: %q, Kind: \"float\", RealBits: math.Float64bits(float64(%s))}", indent, name, typeName, expression)
	case "float64":
		g.line("%s%s := __mrpc.Value{Type: %q, Kind: \"float\", RealBits: math.Float64bits(%s)}", indent, name, typeName, expression)
	case "complex64":
		g.line("%s%s := __mrpc.Value{Type: %q, Kind: \"complex\", RealBits: math.Float64bits(float64(real(%s))), ImagBits: math.Float64bits(float64(imag(%s)))}", indent, name, typeName, expression, expression)
	case "complex128":
		g.line("%s%s := __mrpc.Value{Type: %q, Kind: \"complex\", RealBits: math.Float64bits(real(%s)), ImagBits: math.Float64bits(imag(%s))}", indent, name, typeName, expression, expression)
	case "uint8", "uint16", "uint32", "uint64":
		g.line("%s%s := __mrpc.Value{Type: %q, Kind: \"uint\", Unsigned: uint64(%s)}", indent, name, typeName, expression)
	default:
		if g.isMessage(typ.Name) {
			g.line("%s%s := __mrpcEncode%s(%s)", indent, name, typ.Name, expression)
		} else {
			g.line("%s%s := __mrpc.Value{Type: %q, Kind: \"int\", Signed: int64(%s)}", indent, name, typeName, expression)
		}
	}
}

func (g *generator) decodeValue(name, expression string, typ mrpc.Type, indent string) {
	if g.isResourceType(typ) {
		g.err = fmt.Errorf("resource %s requires a call owner", typ.String())
		return
	}
	sourceType := mgoType(typ)
	wireType := g.wireType(typ)
	switch typ.Kind {
	case mrpc.TypeSlice:
		if typ.Elem.Kind == mrpc.TypeName && typ.Elem.Name == "uint8" && typ.Elem.Qualifier == "" {
			g.line("%svar %s []byte", indent, name)
			g.line("%sif %s.Type != %q { err = __mrpc.NewError(\"protocol\", \"invalid []byte value\"); return }", indent, expression, wireType)
			g.line("%sif %s.Kind == \"bytes\" { %s = append([]byte{}, %s.Bytes...) } else if %s.Kind != \"nil\" { err = __mrpc.NewError(\"protocol\", \"invalid []byte value\"); return }", indent, expression, name, expression, expression)
			return
		}
		g.line("%svar %s %s", indent, name, sourceType)
		g.line("%sif %s.Type != %q { err = __mrpc.NewError(\"protocol\", \"invalid slice value\"); return }", indent, expression, wireType)
		g.line("%sif %s.Kind == \"slice\" {", indent, expression)
		g.line("%s\t%s = make(%s, 0, len(%s.Values))", indent, name, sourceType, expression)
		g.line("%s\tfor _, item := range %s.Values {", indent, expression)
		g.decodeValue("decodedItem", "item", *typ.Elem, indent+"\t\t")
		g.line("%s\t\t%s = append(%s, decodedItem)", indent, name, name)
		g.line("%s\t}", indent)
		g.line("%s} else if %s.Kind != \"nil\" { err = __mrpc.NewError(\"protocol\", \"invalid slice value\"); return }", indent, expression)
	case mrpc.TypeMap:
		g.line("%svar %s %s", indent, name, sourceType)
		g.line("%sif %s.Type != %q { err = __mrpc.NewError(\"protocol\", \"invalid map value\"); return }", indent, expression, wireType)
		g.line("%sif %s.Kind == \"map\" {", indent, expression)
		g.line("%s\t%s = make(%s, len(%s.Entries))", indent, name, sourceType, expression)
		g.line("%s\tfor _, entry := range %s.Entries {", indent, expression)
		g.decodeValue("decodedKey", "entry.Key", *typ.Key, indent+"\t\t")
		g.decodeValue("decodedItem", "entry.Value", *typ.Elem, indent+"\t\t")
		g.line("%s\t\t%s[decodedKey] = decodedItem", indent, name)
		g.line("%s\t}", indent)
		g.line("%s} else if %s.Kind != \"nil\" { err = __mrpc.NewError(\"protocol\", \"invalid map value\"); return }", indent, expression)
	case mrpc.TypeOptional:
		g.line("%svar %s %s", indent, name, sourceType)
		g.line("%sif %s.Type != %q { err = __mrpc.NewError(\"protocol\", \"invalid optional value\"); return }", indent, expression, wireType)
		g.line("%sif %s.Kind == \"optional\" && %s.Optional != nil {", indent, expression, expression)
		g.decodeValue("decodedItem", "(*"+expression+".Optional)", *typ.Elem, indent+"\t")
		g.line("%s\t%s = &decodedItem", indent, name)
		g.line("%s} else if %s.Kind != \"nil\" { err = __mrpc.NewError(\"protocol\", \"invalid optional value\"); return }", indent, expression)
	default:
		g.decodeNamed(name, expression, typ, indent)
	}
}

func (g *generator) decodeNamed(name, expression string, typ mrpc.Type, indent string) {
	typeName := mgoType(typ)
	wireType := g.wireType(typ)
	if typ.Qualifier != "" {
		g.line("%svar %s %s", indent, name, typeName)
		g.line("%s%s, err = %s.Decode%s(%s)", indent, name, typ.Qualifier, typ.Name, expression)
		g.line("%sif err != nil { return }", indent)
		return
	}
	switch typ.Name {
	case "bool":
		g.line("%sif %s.Type != %q || %s.Kind != \"bool\" { err = __mrpc.NewError(\"protocol\", \"invalid bool value\"); return }", indent, expression, wireType, expression)
		g.line("%s%s := %s.Bool", indent, name, expression)
	case "string":
		g.line("%sif %s.Type != %q || %s.Kind != \"string\" { err = __mrpc.NewError(\"protocol\", \"invalid string value\"); return }", indent, expression, wireType, expression)
		g.line("%s%s := %s.Text", indent, name, expression)
	case "float32":
		g.line("%sif %s.Type != %q || %s.Kind != \"float\" { err = __mrpc.NewError(\"protocol\", \"invalid float32 value\"); return }", indent, expression, wireType, expression)
		g.line("%s%s := float32(math.Float64frombits(%s.RealBits))", indent, name, expression)
	case "float64":
		g.line("%sif %s.Type != %q || %s.Kind != \"float\" { err = __mrpc.NewError(\"protocol\", \"invalid float64 value\"); return }", indent, expression, wireType, expression)
		g.line("%s%s := math.Float64frombits(%s.RealBits)", indent, name, expression)
	case "complex64":
		g.line("%sif %s.Type != %q || %s.Kind != \"complex\" { err = __mrpc.NewError(\"protocol\", \"invalid complex64 value\"); return }", indent, expression, wireType, expression)
		g.line("%s%s := complex(float32(math.Float64frombits(%s.RealBits)), float32(math.Float64frombits(%s.ImagBits)))", indent, name, expression, expression)
	case "complex128":
		g.line("%sif %s.Type != %q || %s.Kind != \"complex\" { err = __mrpc.NewError(\"protocol\", \"invalid complex128 value\"); return }", indent, expression, wireType, expression)
		g.line("%s%s := complex(math.Float64frombits(%s.RealBits), math.Float64frombits(%s.ImagBits))", indent, name, expression, expression)
	case "uint8", "uint16", "uint32", "uint64":
		g.line("%sif %s.Type != %q || %s.Kind != \"uint\" { err = __mrpc.NewError(\"protocol\", \"invalid %s value\"); return }", indent, expression, wireType, expression, typ.Name)
		g.line("%s%s := %s(%s.Unsigned)", indent, name, typeName, expression)
		g.line("%sif uint64(%s) != %s.Unsigned { err = __mrpc.NewError(\"protocol\", \"numeric overflow\"); return }", indent, name, expression)
	default:
		if g.isMessage(typ.Name) {
			g.line("%svar %s %s", indent, name, typeName)
			g.line("%s%s, err = __mrpcDecode%s(%s)", indent, name, typ.Name, expression)
			g.line("%sif err != nil { return }", indent)
		} else {
			g.line("%sif %s.Type != %q || %s.Kind != \"int\" { err = __mrpc.NewError(\"protocol\", \"invalid %s value\"); return }", indent, expression, wireType, expression, typ.Name)
			g.line("%s%s := %s(%s.Signed)", indent, name, typeName, expression)
			g.line("%sif int64(%s) != %s.Signed { err = __mrpc.NewError(\"protocol\", \"numeric overflow\"); return }", indent, name, expression)
		}
	}
}

func (g *generator) service(item mrpc.Service) {
	clientType := item.Name + "Client"
	constructor := "new" + exported(clientType)
	binder := "bind" + exported(clientType)
	serve := "serve" + exported(item.Name)
	if isExported(item.Name) {
		constructor = "New" + clientType
		binder = "Bind" + clientType
		serve = "Serve" + item.Name
	}
	g.doc(item.Doc, "")
	g.handlerInterface(item.Name, item.Methods)
	g.line("// %s calls the %s service through its bound RPC route.", clientType, item.Name)
	g.line("type %s struct { client *__mrpc.Client }", clientType)
	g.line("")
	g.line("// %s constructs a client with the supplied binding options.", constructor)
	g.line("func %s(options __mrpc.ClientOptions) *%s {", constructor, clientType)
	g.line("\treturn &%s{client: __mrpc.NewClient(%sContract(), options)}", clientType, item.Name)
	g.line("}")
	g.line("")
	g.line("// %s establishes the exact service binding without invoking a business method.", binder)
	g.line("// An unimplemented binding allows the caller to select a local implementation.")
	g.line("func %s(options __mrpc.ClientOptions) (*%s, error) {", binder, clientType)
	g.line("\tclient := %s(options)", constructor)
	g.line("\tif err := client.client.Bind(); err != nil { return nil, err }")
	g.line("\treturn client, nil")
	g.line("}")
	g.line("")
	g.line("// %sContract returns the service and resource method contract.", item.Name)
	g.line("func %sContract() __mrpc.Contract {", item.Name)
	g.line("\treturn __mrpc.Contract{Protocol: __mrpc.ContractProtocol, Methods: []__mrpc.Method{")
	for _, method := range item.Methods {
		g.line("\t\t%s,", g.methodLiteral(item.Name, method.Name, ""))
	}
	for _, resource := range g.catalog.ServiceResources(item) {
		for _, method := range resource.Methods {
			service := resource.Owner.Namespace + "::" + resource.Name
			g.line("\t\t__mrpc.Method{ID: %q, Service: %q, Name: %q, ContractHash: %q, ResourceTypeHash: %q},", service+"."+method.Name, service, method.Name, resource.Owner.ContractID, resource.Owner.ResourceTypeID(resource.Name))
		}
	}
	g.line("\t}}")
	g.line("}")
	g.line("")
	for _, method := range item.Methods {
		g.clientMethod(clientType, "c", item.Name, method, false)
	}
	g.line("// Close releases the service binding; retained resources own their remaining lifetime.")
	g.line("func (c *%s) Close() error { if c == nil { return nil }; return c.client.Close() }", clientType)
	g.line("")
	for _, method := range item.Methods {
		g.providerMethod(item.Name, method)
	}
	if isExported(item.Name) {
		g.line("// %s runs a pull-based provider until its FFI publication closes.", serve)
	}
	g.line("func %s(handler %sHandler, options __mrpc.ServerOptions) error {", serve, item.Name)
	g.line("\tif handler == nil { return __mrpc.NewError(\"unavailable\", \"MRPC service handler is nil\") }")
	g.line("\tserver, err := __mrpc.NewServer(options, %sContract())", item.Name)
	g.line("\tif err != nil { return err }")
	g.line("\tdefer server.Close()")
	g.line("\tfor {")
	g.line("\t\tevent, err := server.Accept()")
	g.line("\t\tif err != nil { return err }")
	g.line("\t\tif event.Kind == \"cancel\" { server.Cancel(event.RequestID); continue }")
	g.line("\t\tif event.Kind == \"release\" { server.DispatchResource(nil, event); continue }")
	g.line("\t\tcontext, err := server.Begin(event)")
	g.line("\t\tif err != nil { return err }")
	g.line("\t\tif server.DispatchResource(context, event) { continue }")
	g.line("\t\tgo func(event __mrpc.Event) {")
	g.line("\t\t\tvar values []__mrpc.Value")
	g.line("\t\t\tvar callErr error")
	g.line("\t\t\tswitch event.Method.Name {")
	for _, method := range item.Methods {
		g.line("\t\t\tcase %q:", method.Name)
		g.line("\t\t\t\tvalues, callErr = __mrpcInvoke%s%s(context, server, handler, event.Arguments)", item.Name, method.Name)
	}
	g.line("\t\t\tdefault:")
	g.line("\t\t\t\tcallErr = __mrpc.NewError(\"not_found\", \"MRPC method is not implemented\")")
	g.line("\t\t\t}")
	g.line("\t\t\t_ = server.Respond(event.RequestID, values, callErr)")
	g.line("\t\t}(event)")
	g.line("\t}")
	g.line("}")
	g.line("")
}

func (g *generator) resource(item mrpc.Resource) {
	g.doc(item.Doc, "")
	g.handlerInterface(item.Name, item.Methods)
	g.line("// %s references an owned RPC resource.", item.Name)
	g.line("type %s struct { resource *__mrpc.Resource; client *__mrpc.Client }", item.Name)
	hash := g.catalog.ResourceTypeID(item.Name)
	g.line("func %s(client *__mrpc.Client, value __mrpc.Value) (%s, error) { if value.Type == %q && value.Kind == \"nil\" { return %s{}, nil }; resource, err := client.DecodeResource(value, %q); if err != nil { return %s{}, err }; return %s{resource: resource, client: client}, nil }", resourceFunction(mrpc.Type{Name: item.Name}, "New"), item.Name, hash, item.Name, hash, item.Name, item.Name)
	g.line("func %s(client *__mrpc.Client, value %s) (__mrpc.Value, error) { if value.resource == nil { return __mrpc.Value{Type: %q, Kind: \"nil\"}, nil }; return client.Reference(value.resource, %q) }", resourceFunction(mrpc.Type{Name: item.Name}, "Reference"), item.Name, hash, hash)
	g.line("func %s(context *__mrpc.Context, server *__mrpc.Server, handler %sHandler) (__mrpc.Value, error) { if handler == nil { return __mrpc.Value{Type: %q, Kind: \"nil\"}, nil }; resource, err := server.Export(context, handler, %q, __mrpcWrap%s(server, handler)); if err != nil { return __mrpc.Value{}, err }; return __mrpc.Value{Type: %q, Kind: \"resource\", Resource: resource}, nil }", resourceFunction(mrpc.Type{Name: item.Name}, "Export"), item.Name, hash, hash, item.Name, hash)
	g.line("func %s(context *__mrpc.Context, server *__mrpc.Server, value __mrpc.Value) (%sHandler, error) { if err := context.Err(); err != nil { return nil, err }; if value.Type == %q && value.Kind == \"nil\" { return nil, nil }; if value.Type != %q || value.Kind != \"resource\" || value.Resource == nil || value.Resource.TypeHash != %q { return nil, __mrpc.NewError(\"invalid_argument\", \"invalid resource type\") }; raw, ok := server.ResourceValue(value.Resource); if !ok { return nil, __mrpc.NewError(\"not_found\", \"resource is closed\") }; handler, ok := raw.(%sHandler); if !ok { return nil, __mrpc.NewError(\"protocol\", \"invalid resource handler\") }; return handler, nil }", resourceFunction(mrpc.Type{Name: item.Name}, "Resolve"), item.Name, hash, hash, hash, item.Name)
	g.line("")
	for _, method := range item.Methods {
		g.clientMethod(item.Name, "r", item.Name, method, true)
	}
	g.line("// Close releases the remote resource and invalidates this handle.")
	g.line("func (r *%s) Close() error {", item.Name)
	g.line("\tif r == nil || r.client == nil { return nil }")
	g.line("\terr := r.client.Release(r.resource)")
	g.line("\tif err == nil { r.client = nil; r.resource = nil }")
	g.line("\treturn err")
	g.line("}")
	g.line("")
	for _, method := range item.Methods {
		g.providerMethod(item.Name, method)
	}
	g.line("func __mrpcWrap%s(server *__mrpc.Server, handler %sHandler) __mrpc.ResourceHandler {", item.Name, item.Name)
	g.line("\treturn func(context *__mrpc.Context, method __mrpc.Method, arguments []__mrpc.Value) ([]__mrpc.Value, error) {")
	g.line("\t\tswitch method.Name {")
	for _, method := range item.Methods {
		g.line("\t\tcase %q:", method.Name)
		g.line("\t\t\treturn __mrpcInvoke%s%s(context, server, handler, arguments)", item.Name, method.Name)
	}
	g.line("\t\t}")
	g.line("\t\treturn nil, __mrpc.NewError(\"not_found\", \"MRPC resource method is not implemented\")")
	g.line("\t}")
	g.line("}")
	g.line("")
}

func (g *generator) handlerInterface(name string, methods []mrpc.Method) {
	g.line("type %sHandler interface {", name)
	for _, method := range methods {
		g.doc(method.Doc, "\t")
		params := make([]string, len(method.Params)+1)
		params[0] = "context *__mrpc.Context"
		for i, field := range method.Params {
			params[i+1] = field.Name + " " + g.providerType(field.Type)
		}
		results := make([]string, 0, len(method.Results)+1)
		for _, field := range method.Results {
			results = append(results, field.Name+" "+g.providerType(field.Type))
		}
		results = append(results, "err error")
		g.line("\t%s(%s) (%s)", method.Name, strings.Join(params, ", "), strings.Join(results, ", "))
	}
	g.line("}")
	g.line("")
}

func (g *generator) providerMethod(owner string, method mrpc.Method) {
	handlerType := owner + "Handler"
	g.line("func __mrpcInvoke%s%s(context *__mrpc.Context, server *__mrpc.Server, handler %s, arguments []__mrpc.Value) (values []__mrpc.Value, err error) {", owner, method.Name, handlerType)
	g.line("\tdefer func() { if recover() != nil { values = nil; err = __mrpc.NewError(\"internal\", \"MRPC handler panicked\") } }()")
	g.line("\tif len(arguments) != %d { return nil, __mrpc.NewError(\"invalid_argument\", \"invalid MRPC argument count\") }", len(method.Params))
	args := make([]string, len(method.Params))
	for i, field := range method.Params {
		args[i] = fmt.Sprintf("argument%d", i)
		if g.isResourceType(field.Type) {
			g.line("\targument%d, resolveErr := %s(context, server, arguments[%d]); if resolveErr != nil { return nil, resolveErr }", i, resourceFunction(field.Type, "Resolve"), i)
		} else {
			g.decodeValue(fmt.Sprintf("argument%d", i), fmt.Sprintf("arguments[%d]", i), field.Type, "\t")
		}
	}
	resultNames := make([]string, len(method.Results))
	for i := range method.Results {
		resultNames[i] = fmt.Sprintf("result%d", i)
	}
	callResults := append(append([]string(nil), resultNames...), "callErr")
	handlerArgs := append([]string{"context"}, args...)
	g.line("\t%s := handler.%s(%s)", strings.Join(callResults, ", "), method.Name, strings.Join(handlerArgs, ", "))
	g.line("\tif callErr != nil { return nil, callErr }")
	g.line("\tvalues = make([]__mrpc.Value, 0, %d)", len(method.Results))
	for i, field := range method.Results {
		if g.isResourceType(field.Type) {
			g.line("\tencoded%d, exportErr := %s(context, server, result%d)", i, resourceFunction(field.Type, "Export"), i)
			g.line("\tif exportErr != nil { return nil, exportErr }")
		} else {
			g.encodeValue(fmt.Sprintf("encoded%d", i), fmt.Sprintf("result%d", i), field.Type, "\t")
		}
		g.line("\tvalues = append(values, encoded%d)", i)
	}
	g.line("\treturn values, nil")
	g.line("}")
	g.line("")
}

func (g *generator) clientMethod(receiverType, receiver, owner string, method mrpc.Method, resource bool) {
	method.Params = append([]mrpc.Field(nil), method.Params...)
	method.Results = append([]mrpc.Field(nil), method.Results...)
	for i := range method.Params {
		method.Params[i].Name = "arg" + strconv.Itoa(i)
	}
	for i := range method.Results {
		method.Results[i].Name = "out" + strconv.Itoa(i)
	}
	g.doc(method.Doc, "")
	params := []string{}
	for _, field := range method.Params {
		params = append(params, field.Name+" "+mgoType(field.Type))
	}
	results := make([]string, 0, len(method.Results)+1)
	for _, field := range method.Results {
		results = append(results, field.Name+" "+mgoType(field.Type))
	}
	results = append(results, "err error")
	g.line("func (%s *%s) %s(%s) (%s) {", receiver, receiverType, method.Name, strings.Join(params, ", "), strings.Join(results, ", "))
	if len(method.Results) != 0 {
		g.line("\tdefer func() { if err != nil {")
		for i, field := range method.Results {
			g.line("\t\tvar zero%d %s; %s = zero%d", i, mgoType(field.Type), field.Name, i)
		}
		g.line("\t} }()")
	}
	client := receiver + ".client"
	if resource {
		g.line("\tif %s == nil || %s.resource == nil || %s.resource.ObjectID == 0 || %s.client == nil { err = __mrpc.NewError(\"not_found\", \"resource is closed\"); return }", receiver, receiver, receiver, receiver)
	}
	g.line("\targuments := make([]__mrpc.Value, 0, %d)", len(method.Params))
	for i, field := range method.Params {
		if g.isResourceType(field.Type) {
			g.line("\targument%d, referenceErr := %s(%s, %s); if referenceErr != nil { err = referenceErr; return }", i, resourceFunction(field.Type, "Reference"), client, field.Name)
		} else {
			g.encodeValue("argument"+strconv.Itoa(i), field.Name, field.Type, "\t")
		}
		g.line("\targuments = append(arguments, argument%d)", i)
	}
	receiverExpr := "nil"
	resourceHash := ""
	if resource {
		receiverExpr = receiver + ".resource"
		resourceHash = g.catalog.ResourceTypeID(owner)
	}
	callResult := gen.LocalName(method, "__mrpcResult")
	g.line("\t%s, callErr := %s.CallOwned(%s, %s, arguments)", callResult, client, g.methodLiteral(owner, method.Name, resourceHash), receiverExpr)
	g.line("\tif callErr != nil { err = callErr; return }")
	g.line("\tdefer %s.Discard(); values := %s.Values", callResult, callResult)
	g.line("\tif len(values) != %d { err = __mrpc.NewError(\"protocol\", \"invalid result count\"); return }", len(method.Results))
	for i, field := range method.Results {
		if g.isResourceType(field.Type) {
			g.line("\t%s, err = %s(%s, values[%d]); if err != nil { return }", field.Name, resourceFunction(field.Type, "New"), client, i)
		} else {
			g.decodeValue("decoded"+strconv.Itoa(i), fmt.Sprintf("values[%d]", i), field.Type, "\t")
			g.line("\t%s = decoded%d", field.Name, i)
		}
	}
	g.line("\terr = %s.Accept()", callResult)
	g.line("\treturn")
	g.line("}")
	g.line("")
}

func (g *generator) methodLiteral(owner, method, resourceHash string) string {
	service := g.catalog.Namespace + "::" + owner
	return fmt.Sprintf("__mrpc.Method{ID: %q, Service: %q, Name: %q, ContractHash: mrpcContractID, ResourceTypeHash: %q}", service+"."+method, service, method, resourceHash)
}

func isExported(name string) bool {
	return name != "" && name[0] >= 'A' && name[0] <= 'Z'
}

func (g *generator) wireType(typ mrpc.Type) string {
	if g.err != nil {
		return ""
	}
	value, err := g.catalog.CanonicalType(typ)
	if err != nil {
		g.err = err
	}
	return value
}

func (g *generator) providerType(typ mrpc.Type) string {
	if g.isResourceType(typ) {
		return mgoType(typ) + "Handler"
	}
	return mgoType(typ)
}

func (g *generator) isMessage(name string) bool {
	for _, file := range g.catalog.Files {
		for _, item := range file.Messages {
			if item.Name == name {
				return true
			}
		}
	}
	return false
}

func (g *generator) isResourceType(typ mrpc.Type) bool {
	resolved, err := g.catalog.ResolveType(typ)
	return err == nil && resolved.Kind == "resource"
}

func resourceFunction(typ mrpc.Type, prefix string) string {
	if len(typ.Name) > 0 && typ.Name[0] >= 'a' && typ.Name[0] <= 'z' {
		prefix = strings.ToLower(prefix[:1]) + prefix[1:]
	}
	if typ.Qualifier != "" {
		return typ.Qualifier + "." + prefix + typ.Name
	}
	return prefix + typ.Name
}
