// Package gogen generates typed Go bindings from language-independent MRPC schemas.
package gogen

import (
	"bytes"
	"errors"
	"fmt"
	"go/format"
	"sort"
	"strconv"
	"strings"

	"github.com/d7z-team/mini-go/tooling/mrpc"
	"github.com/d7z-team/mini-go/tooling/mrpc/gen"
)

// Options controls Go package naming without affecting contract identity.
type Options struct {
	Package string
	Prefix  string
}

// Generate emits formatted Go client, provider, handler, and codec source.
func Generate(catalog mrpc.Catalog, options Options) ([]byte, error) {
	canonical, err := gen.CanonicalCatalog(catalog)
	if err != nil {
		return nil, fmt.Errorf("generate Go MRPC: %w", err)
	}
	catalog = canonical
	packageName := strings.TrimSpace(options.Package)
	if packageName == "" {
		packageName = goPackageName(catalog.Options["go_package"])
	}
	if packageName == "" {
		return nil, errors.New("generate Go MRPC: package is required")
	}
	prefix := options.Prefix
	if prefix == "" {
		prefix = catalog.Options["go_prefix"]
	}
	g := generator{catalog: catalog, prefix: prefix}
	g.line("// Code generated by mini-go rpc generate; DO NOT EDIT.")
	g.line("")
	g.line("package %s", packageName)
	g.line("")
	g.line("import (")
	g.line("\t\"context\"")
	g.line("\t\"fmt\"")
	g.line("")
	g.line("\tminigorpc \"github.com/d7z-team/mini-go/rpc\"")
	aliases := make(map[string]string)
	paths := make(map[string]string)
	for _, file := range catalog.Files {
		for _, imported := range file.Imports {
			dependency, ok := catalog.Dependencies[imported.Path]
			if !ok {
				return nil, fmt.Errorf("generate Go MRPC: missing imported catalog %q", imported.Path)
			}
			path := strings.TrimSpace(dependency.Options["go_package"])
			if separator := strings.IndexByte(path, ';'); separator >= 0 {
				path = path[:separator]
			}
			if path == "" {
				return nil, fmt.Errorf("generate Go MRPC: import %q has no go_package option", imported.Path)
			}
			if previous, ok := aliases[imported.Alias]; ok && previous != path {
				return nil, fmt.Errorf("generate Go MRPC: import alias %q maps to both %q and %q", imported.Alias, previous, path)
			}
			if previous, ok := paths[path]; ok {
				if previous != imported.Alias {
					return nil, fmt.Errorf("generate Go MRPC: import %q uses both aliases %q and %q", path, previous, imported.Alias)
				}
				continue
			}
			aliases[imported.Alias] = path
			paths[path] = imported.Alias
			g.line("\t%s %q", imported.Alias, path)
		}
	}
	g.line(")")
	g.line("")
	g.line("const MRPCContractID = %q", catalog.ContractID)
	for _, file := range catalog.Files {
		for _, item := range file.Enums {
			g.enum(item)
		}
		for _, item := range file.Messages {
			g.message(item)
			g.messageCodec(item)
		}
		for _, item := range file.Resources {
			g.resourceInterface(item)
		}
	}
	for _, file := range catalog.Files {
		for _, item := range file.Resources {
			g.resourceAdapter(item)
		}
		for _, item := range file.Services {
			g.service(item)
		}
	}
	g.contract()
	if g.err != nil {
		return nil, fmt.Errorf("generate Go MRPC: %w", g.err)
	}
	formatted, err := format.Source(g.source.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated Go MRPC: %w\n%s", err, g.source.Bytes())
	}
	return formatted, nil
}

func (g *generator) contract() {
	g.line("func Contract() minigorpc.Contract { return minigorpc.Contract{Protocol: minigorpc.ContractProtocol, Methods: []minigorpc.Method{")
	imported := map[string]bool{}
	for _, file := range g.catalog.Files {
		for _, service := range file.Services {
			for _, method := range service.Methods {
				g.line("\t%s,", g.methodLiteral(service.Name, method.Name, ""))
			}
			for _, resource := range g.catalog.ServiceResources(service) {
				key := resource.Owner.ContractID + "/" + resource.Name
				if resource.Owner.ContractID == g.catalog.ContractID || imported[key] {
					continue
				}
				imported[key] = true
				for _, method := range resource.Methods {
					g.line("\t%s,", resourceMethodLiteral(resource, method.Name))
				}
			}
		}
		for _, resource := range file.Resources {
			for _, method := range resource.Methods {
				g.line("\t%s,", g.methodLiteral(resource.Name, method.Name, g.catalog.ResourceTypeID(resource.Name)))
			}
		}
	}
	g.line("}} }")
}

type generator struct {
	catalog mrpc.Catalog
	prefix  string
	source  bytes.Buffer
	err     error
}

func (g *generator) line(format string, args ...any) {
	if len(args) == 0 {
		g.source.WriteString(format)
	} else {
		fmt.Fprintf(&g.source, format, args...)
	}
	g.source.WriteByte('\n')
}

func (g *generator) doc(doc, indent string) {
	for _, line := range strings.Split(strings.TrimSpace(doc), "\n") {
		if line != "" {
			g.line("%s// %s", indent, line)
		}
	}
}

func goPackageName(value string) string {
	if index := strings.LastIndex(value, ";"); index >= 0 {
		return strings.TrimSpace(value[index+1:])
	}
	if index := strings.LastIndex(value, "/"); index >= 0 {
		value = value[index+1:]
	}
	return strings.TrimSpace(value)
}

func exported(name string) string {
	if name == "" {
		return "Value"
	}
	return strings.ToUpper(name[:1]) + name[1:]
}

func (g *generator) enum(item mrpc.Enum) {
	typeName := g.typeName(item.Name)
	g.doc(item.Doc, "")
	g.line("type %s int32", typeName)
	g.line("const (")
	for _, value := range item.Values {
		g.doc(value.Doc, "\t")
		g.line("\t%s%s %s = %d", g.prefix, value.Name, typeName, value.Number)
	}
	g.line(")")
	wire := g.catalog.Namespace + "." + item.Name
	g.line("func Encode%s(value %s) (minigorpc.Value, error) { return minigorpc.Value{Type: %q, Data: int64(value)}, nil }", typeName, typeName, wire)
	g.line("func Decode%s(value minigorpc.Value) (%s, error) { raw, ok := value.Data.(int64); if value.Type != %q || !ok || raw < -2147483648 || raw > 2147483647 { return 0, minigorpc.StatusError{Code: minigorpc.CodeProtocol, Message: \"invalid enum value\"} }; return %s(raw), nil }", typeName, typeName, wire, typeName)
}

func (g *generator) message(item mrpc.Message) {
	g.doc(item.Doc, "")
	g.line("type %s struct {", g.typeName(item.Name))
	fields := append([]mrpc.Field(nil), item.Fields...)
	sort.Slice(fields, func(i, j int) bool { return fields[i].ID < fields[j].ID })
	for _, field := range fields {
		g.doc(field.Doc, "\t")
		g.line("\t%s %s", exported(field.Name), g.goType(field.Type, false))
	}
	g.line("}")
}

func (g *generator) messageCodec(item mrpc.Message) {
	name := g.typeName(item.Name)
	fields := append([]mrpc.Field(nil), item.Fields...)
	sort.Slice(fields, func(i, j int) bool { return fields[i].ID < fields[j].ID })
	g.line("func Encode%s(value %s) (out minigorpc.Value, err error) {", name, name)
	g.line("\tfields := make([]minigorpc.Field, 0, %d)", len(fields))
	for index, field := range fields {
		g.encodeValue("encoded"+strconv.Itoa(index), "value."+exported(field.Name), field.Type, "\t")
		g.line("\tfields = append(fields, minigorpc.Field{ID: %d, Value: encoded%d})", field.ID, index)
	}
	g.line("\tout = minigorpc.Value{Type: %q, Data: fields}; return", g.catalog.Namespace+"."+item.Name)
	g.line("}")
	g.line("func Decode%s(value minigorpc.Value) (out %s, err error) {", name, name)
	g.line("\tif value.Type != %q { return out, minigorpc.StatusError{Code: minigorpc.CodeProtocol, Message: \"invalid %s value\"} }", g.catalog.Namespace+"."+item.Name, name)
	g.line("\tfields, ok := value.Data.([]minigorpc.Field); if !ok { return out, minigorpc.StatusError{Code: minigorpc.CodeProtocol, Message: \"invalid %s fields\"} }", name)
	for index := range fields {
		g.line("\tfound%d := false", index)
	}
	g.line("\tfor _, field := range fields {")
	g.line("\t\tswitch field.ID {")
	for index, field := range fields {
		g.line("\t\tcase %d:", field.ID)
		g.line("\t\t\tif found%d { return out, minigorpc.StatusError{Code: minigorpc.CodeProtocol, Message: %q} }", index, "duplicate "+name+"."+exported(field.Name))
		g.decodeValue("decoded"+strconv.Itoa(index), "field.Value", field.Type, "\t\t\t")
		g.line("\t\t\tout.%s, found%d = decoded%d, true", exported(field.Name), index, index)
	}
	g.line("\t\tdefault: return out, minigorpc.StatusError{Code: minigorpc.CodeProtocol, Message: \"unknown MRPC field ID\"}")
	g.line("\t\t}")
	g.line("\t}")
	for index, field := range fields {
		g.line("\tif !found%d { return out, minigorpc.StatusError{Code: minigorpc.CodeProtocol, Message: %q} }", index, "missing "+name+"."+exported(field.Name))
	}
	g.line("\treturn out, nil")
	g.line("}")
}

func (g *generator) resourceInterface(item mrpc.Resource) {
	name := g.typeName(item.Name)
	g.doc(item.Doc, "")
	g.line("type %sHandler interface {", name)
	for _, method := range item.Methods {
		g.doc(method.Doc, "\t")
		g.handlerSignature(method)
	}
	g.line("\tClose(context.Context) error")
	g.line("}")
	g.line("type %sClient struct { state *minigorpc.ResourceHandle }", name)
	hash := g.catalog.ResourceTypeID(item.Name)
	g.line("func New%sClient(ctx context.Context, routes *minigorpc.RouteSet, value minigorpc.Value) (*%sClient, error) { if err := ctx.Err(); err != nil { return nil, err }; if value.Type == %q && value.Resource == nil && value.Data == nil { return nil, nil }; if value.Type != %q || value.Resource == nil || value.Resource.TypeHash != %q { return nil, minigorpc.StatusError{Code: minigorpc.CodeProtocol, Message: \"invalid resource value\"} }; handle, err := routes.BindResource(*value.Resource); if err != nil { return nil, err }; return &%sClient{state: handle}, nil }", name, name, hash, hash, hash, name)
	g.line("func Reference%s(ctx context.Context, routes *minigorpc.RouteSet, value *%sClient) (minigorpc.Value, error) { if value == nil { return minigorpc.Value{Type: %q}, nil }; return value.state.Reference(ctx, routes) }", name, name, hash)
	g.line("func Export%s(ctx context.Context, handler %sHandler) (minigorpc.Value, error) { if handler == nil { return minigorpc.Value{Type: %q}, nil }; return minigorpc.Export(ctx, &mrpc%sResource{handler: handler}, %q) }", name, name, hash, name, hash)
	g.line("func Resolve%s(ctx context.Context, value minigorpc.Value) (%sHandler, error) { if value.Type == %q && value.Resource == nil && value.Data == nil { return nil, nil }; if value.Type != %q || value.Resource == nil || value.Resource.TypeHash != %q { return nil, minigorpc.StatusError{Code: minigorpc.CodeInvalidArgument, Message: \"resource type mismatch\"} }; resource, err := minigorpc.Resolve(ctx, *value.Resource); if err != nil { return nil, err }; typed, ok := resource.(*mrpc%sResource); if !ok { return nil, minigorpc.StatusError{Code: minigorpc.CodeInvalidArgument, Message: \"resource handler mismatch\"} }; return typed.handler, nil }", name, name, hash, hash, hash, name)
}

func (g *generator) handlerSignature(method mrpc.Method) {
	params := []string{"context.Context"}
	for _, field := range method.Params {
		params = append(params, g.goType(field.Type, true))
	}
	results := make([]string, 0, len(method.Results)+1)
	for _, field := range method.Results {
		results = append(results, g.goType(field.Type, true))
	}
	results = append(results, "error")
	g.line("\t%s(%s) (%s)", method.Name, strings.Join(params, ", "), strings.Join(results, ", "))
}

func (g *generator) resourceAdapter(item mrpc.Resource) {
	name := g.typeName(item.Name)
	g.line("type mrpc%sResource struct { handler %sHandler }", name, name)
	g.line("func (r *mrpc%sResource) Invoke(ctx context.Context, method string, arguments []minigorpc.Value) (values []minigorpc.Value, err error) {", name)
	g.line("\tdefer func() { if recover() != nil { values = nil; err = minigorpc.StatusError{Code: minigorpc.CodeInternal, Message: \"MRPC handler panicked\"} } }()")
	g.line("\tif r == nil || r.handler == nil { return nil, minigorpc.StatusError{Code: minigorpc.CodeUnavailable, Message: \"resource handler is unavailable\"} }")
	g.line("\tswitch method {")
	for _, method := range item.Methods {
		g.line("\tcase %q:", method.Name)
		g.invokeHandler("r.handler", method, "\t\t")
	}
	g.line("%s", "\tdefault: return nil, fmt.Errorf(\"unknown resource method %q\", method)")
	g.line("\t}")
	g.line("}")
	g.line("func (r *mrpc%sResource) Close(ctx context.Context) error { if r == nil || r.handler == nil { return nil }; return r.handler.Close(ctx) }", name)
	for _, method := range item.Methods {
		g.clientMethod(name, "c", item.Name, method, true)
	}
	g.line("func (c *%sClient) Close(ctx context.Context) error {", name)
	g.line("\tif c == nil { return nil }; return c.state.Close(ctx)")
	g.line("}")
}

func (g *generator) service(item mrpc.Service) {
	name := g.typeName(item.Name)
	resources := g.catalog.ServiceResources(item)
	g.doc(item.Doc, "")
	g.line("type %sHandler interface {", name)
	for _, method := range item.Methods {
		g.doc(method.Doc, "\t")
		g.handlerSignature(method)
	}
	g.line("}")
	for _, method := range item.Methods {
		g.line("func invoke%s%s(handler %sHandler) minigorpc.MethodHandler {", name, method.Name, name)
		g.line("\treturn func(ctx context.Context, arguments []minigorpc.Value) (values []minigorpc.Value, err error) {")
		g.line("\t\tdefer func() { if recover() != nil { values = nil; err = minigorpc.StatusError{Code: minigorpc.CodeInternal, Message: \"MRPC handler panicked\"} } }()")
		g.line("\t\tif handler == nil { return nil, minigorpc.StatusError{Code: minigorpc.CodeUnavailable, Message: \"service handler is unavailable\"} }")
		g.invokeHandler("handler", method, "\t\t")
		g.line("\t}")
		g.line("}")
	}
	g.line("func New%sProvider(handler %sHandler) (minigorpc.Provider, error) {", name, name)
	g.line("\tprovider, err := minigorpc.NewProvider(")
	for _, method := range item.Methods {
		g.line("\t\tminigorpc.MethodBinding{Method: %s, Invoke: invoke%s%s(handler)},", g.methodLiteral(item.Name, method.Name, ""), name, method.Name)
	}
	for _, resource := range resources {
		for _, method := range resource.Methods {
			g.line("\t\tminigorpc.MethodBinding{Method: %s},", resourceMethodLiteral(resource, method.Name))
		}
	}
	g.line("\t); return provider, err")
	g.line("}")
	g.line("type %sClient struct { routes *minigorpc.RouteSet }", name)
	g.line("func Bind%sClient(ctx context.Context, binder minigorpc.Binder, options minigorpc.BindOptions) (*%sClient, error) {", name, name)
	g.line("\tif binder == nil { return nil, fmt.Errorf(\"MRPC binder is required\") }")
	g.line("\troutes, err := binder.Bind(ctx, minigorpc.BindRequest{Contract: %sContract(), Options: options}); if err != nil { return nil, err }; return &%sClient{routes: routes}, nil", name, name)
	g.line("}")
	g.line("func %sContract() minigorpc.Contract { return minigorpc.Contract{Protocol: minigorpc.ContractProtocol, Methods: []minigorpc.Method{", name)
	for _, method := range item.Methods {
		g.line("\t%s,", g.methodLiteral(item.Name, method.Name, ""))
	}
	for _, resource := range resources {
		for _, method := range resource.Methods {
			g.line("\t%s,", resourceMethodLiteral(resource, method.Name))
		}
	}
	g.line("}} }")
	for _, method := range item.Methods {
		g.clientMethod(name, "c", item.Name, method, false)
	}
	g.line("func (c *%sClient) Close() error { if c == nil || c.routes == nil { return nil }; return c.routes.Close() }", name)
}

func (g *generator) invokeHandler(handler string, method mrpc.Method, indent string) {
	g.line("%sif len(arguments) != %d { return nil, minigorpc.StatusError{Code: minigorpc.CodeInvalidArgument, Message: \"invalid argument count\"} }", indent, len(method.Params))
	args := make([]string, len(method.Params))
	for i, field := range method.Params {
		args[i] = fmt.Sprintf("argument%d", i)
		if g.isResourceType(field.Type) {
			g.line("%sargument%d, resolveErr := %s(ctx, arguments[%d]); if resolveErr != nil { return nil, resolveErr }", indent, i, g.resourceFunction(field.Type, "Resolve", ""), i)
		} else {
			g.decodeValue(fmt.Sprintf("argument%d", i), fmt.Sprintf("arguments[%d]", i), field.Type, indent)
		}
	}
	resultNames := make([]string, len(method.Results))
	for i, field := range method.Results {
		resultNames[i] = fmt.Sprintf("result%d", i)
		g.line("%svar result%d %s", indent, i, g.goType(field.Type, true))
	}
	callResults := append(append([]string(nil), resultNames...), "err")
	callArguments := ""
	if len(args) != 0 {
		callArguments = ", " + strings.Join(args, ", ")
	}
	g.line("%s%s = %s.%s(ctx%s); if err != nil { return nil, err }", indent, strings.Join(callResults, ", "), handler, method.Name, callArguments)
	g.line("%svalues = make([]minigorpc.Value, 0, %d)", indent, len(method.Results))
	for i, field := range method.Results {
		if g.isResourceType(field.Type) {
			g.line("%svar encoded%d minigorpc.Value; encoded%d, err = %s(ctx, result%d); if err != nil { return nil, err }", indent, i, i, g.resourceFunction(field.Type, "Export", ""), i)
		} else {
			g.encodeValue(fmt.Sprintf("encoded%d", i), fmt.Sprintf("result%d", i), field.Type, indent)
		}
		g.line("%svalues = append(values, encoded%d)", indent, i)
	}
	g.line("%sreturn values, nil", indent)
}

func (g *generator) clientMethod(receiver, variable, owner string, method mrpc.Method, resource bool) {
	method.Params = append([]mrpc.Field(nil), method.Params...)
	method.Results = append([]mrpc.Field(nil), method.Results...)
	for i := range method.Params {
		method.Params[i].Name = "arg" + strconv.Itoa(i)
	}
	for i := range method.Results {
		method.Results[i].Name = "out" + strconv.Itoa(i)
	}
	params := []string{"ctx context.Context"}
	for _, field := range method.Params {
		params = append(params, field.Name+" "+g.goType(field.Type, false))
	}
	results := make([]string, 0, len(method.Results)+1)
	for _, field := range method.Results {
		results = append(results, field.Name+" "+g.goType(field.Type, false))
	}
	results = append(results, "err error")
	g.line("func (%s *%sClient) %s(%s) (%s) {", variable, receiver, method.Name, strings.Join(params, ", "), strings.Join(results, ", "))
	if len(method.Results) != 0 {
		g.line("\tdefer func() { if err != nil {")
		for i, field := range method.Results {
			g.line("\t\tvar zero%d %s; %s = zero%d", i, g.goType(field.Type, false), field.Name, i)
		}
		g.line("\t} }()")
	}
	if resource {
		g.line("\tif %s == nil { err = minigorpc.StatusError{Code: minigorpc.CodeNotFound, Message: \"nil resource\"}; return }; receiverValue, referenceErr := %s.state.Reference(ctx, %s.state.RouteSet()); if referenceErr != nil { err = referenceErr; return }", variable, variable, variable)
	}
	routes := variable + ".routes"
	if resource {
		routes = variable + ".state.RouteSet()"
	}
	g.line("\targuments := make([]minigorpc.Value, 0, %d)", len(method.Params))
	for i, field := range method.Params {
		if g.isResourceType(field.Type) {
			g.line("\tencoded%d, referenceErr := %s(ctx, %s, %s); if referenceErr != nil { err = referenceErr; return }", i, g.resourceFunction(field.Type, "Reference", ""), routes, field.Name)
		} else {
			g.encodeValue(fmt.Sprintf("encoded%d", i), field.Name, field.Type, "\t")
		}
		g.line("\targuments = append(arguments, encoded%d)", i)
	}
	receiverRef := "nil"
	if resource {
		receiverRef = "receiverValue.Resource"
	}
	g.line("\tresult, callErr := %s.Call(ctx, minigorpc.Call{Method: %s, Receiver: %s, Arguments: arguments}); if callErr != nil { err = callErr; return }; defer result.Discard(context.Background())", routes, g.methodLiteral(owner, method.Name, func() string {
		if resource {
			return g.catalog.ResourceTypeID(owner)
		}
		return ""
	}()), receiverRef)
	g.line("\tif len(result.Values) != %d { err = fmt.Errorf(\"MRPC method returned %%d values, want %d\", len(result.Values)); return }", len(method.Results), len(method.Results))
	for i, field := range method.Results {
		if g.isResourceType(field.Type) {
			g.line("\t%s, err = %s(ctx, %s, result.Values[%d]); if err != nil { return }", field.Name, g.resourceFunction(field.Type, "New", "Client"), routes, i)
		} else {
			g.decodeValue("decoded"+strconv.Itoa(i), fmt.Sprintf("result.Values[%d]", i), field.Type, "\t")
			g.line("\t%s = decoded%d", field.Name, i)
		}
	}
	g.line("\tif acceptErr := result.Accept(ctx); acceptErr != nil { err = acceptErr }; return")
	g.line("}")
}

func (g *generator) methodLiteral(owner, method, resourceHash string) string {
	service := g.catalog.Namespace + "::" + owner
	return fmt.Sprintf("minigorpc.Method{ID: %q, Service: %q, Name: %q, ContractHash: MRPCContractID, ResourceTypeHash: %q}", service+"."+method, service, method, resourceHash)
}

func resourceMethodLiteral(resource mrpc.ResolvedResource, method string) string {
	service := resource.Owner.Namespace + "::" + resource.Name
	return fmt.Sprintf("minigorpc.Method{ID: %q, Service: %q, Name: %q, ContractHash: %q, ResourceTypeHash: %q}", service+"."+method, service, method, resource.Owner.ContractID, resource.Owner.ResourceTypeID(resource.Name))
}

func (g *generator) wireType(typ mrpc.Type) string {
	if g.err != nil {
		return ""
	}
	value, err := g.catalog.CanonicalType(typ)
	if err != nil {
		g.err = err
	}
	return value
}

func (g *generator) goType(typ mrpc.Type, provider bool) string {
	switch typ.Kind {
	case mrpc.TypeSlice:
		return "[]" + g.goType(*typ.Elem, provider)
	case mrpc.TypeMap:
		return "map[" + g.goType(*typ.Key, provider) + "]" + g.goType(*typ.Elem, provider)
	case mrpc.TypeOptional:
		return "*" + g.goType(*typ.Elem, provider)
	}
	if typ.Qualifier != "" {
		if g.isResourceType(typ) {
			if provider {
				return typ.Qualifier + "." + g.importedTypeName(typ.Qualifier, typ.Name) + "Handler"
			}
			return "*" + typ.Qualifier + "." + g.importedTypeName(typ.Qualifier, typ.Name) + "Client"
		}
		return typ.Qualifier + "." + g.importedTypeName(typ.Qualifier, typ.Name)
	}
	if provider && g.isResource(typ.Name) {
		return g.typeName(typ.Name) + "Handler"
	}
	if !provider && g.isResource(typ.Name) {
		return "*" + g.typeName(typ.Name) + "Client"
	}
	if _, scalar := scalarGoTypes[typ.Name]; scalar {
		return typ.Name
	}
	return g.typeName(typ.Name)
}

var scalarGoTypes = map[string]struct{}{
	"bool": {}, "string": {},
	"int8": {}, "int16": {}, "int32": {}, "int64": {},
	"uint8": {}, "uint16": {}, "uint32": {}, "uint64": {},
	"float32": {}, "float64": {}, "complex64": {}, "complex128": {},
}

func (g *generator) encodeValue(name, expression string, typ mrpc.Type, indent string) {
	if g.isResourceType(typ) {
		g.err = fmt.Errorf("resource %s requires a call owner", typ.String())
		return
	}
	wireType := g.wireType(typ)
	switch typ.Kind {
	case mrpc.TypeSlice:
		if typ.Elem.Kind == mrpc.TypeName && typ.Elem.Qualifier == "" && typ.Elem.Name == "uint8" {
			g.line("%s%s := minigorpc.Value{Type: %q}; if %s != nil { %s.Data = append([]byte{}, %s...) }", indent, name, wireType, expression, name, expression)
			return
		}
		g.line("%s%s := minigorpc.Value{Type: %q}", indent, name, wireType)
		g.line("%sif %s != nil {", indent, expression)
		g.line("%s\titems := make([]minigorpc.Value, 0, len(%s))", indent, expression)
		g.line("%s\tfor _, item := range %s {", indent, expression)
		g.encodeValue("encodedItem", "item", *typ.Elem, indent+"\t\t")
		g.line("%s\t\titems = append(items, encodedItem)", indent)
		g.line("%s\t}", indent)
		g.line("%s\t%s.Data = items", indent, name)
		g.line("%s}", indent)
	case mrpc.TypeMap:
		g.line("%s%s := minigorpc.Value{Type: %q}", indent, name, wireType)
		g.line("%sif %s != nil {", indent, expression)
		g.line("%s\tentries := make([]minigorpc.MapEntry, 0, len(%s))", indent, expression)
		g.line("%s\tfor key, item := range %s {", indent, expression)
		g.encodeValue("encodedKey", "key", *typ.Key, indent+"\t\t")
		g.encodeValue("encodedItem", "item", *typ.Elem, indent+"\t\t")
		g.line("%s\t\tentries = append(entries, minigorpc.MapEntry{Key: encodedKey, Value: encodedItem})", indent)
		g.line("%s\t}", indent)
		g.line("%s\t%s.Data = entries", indent, name)
		g.line("%s}", indent)
	case mrpc.TypeOptional:
		g.line("%s%s := minigorpc.Value{Type: %q}", indent, name, wireType)
		g.line("%sif %s != nil {", indent, expression)
		g.encodeValue("encodedItem", "*"+expression, *typ.Elem, indent+"\t")
		g.line("%s\t%s.Data = encodedItem", indent, name)
		g.line("%s}", indent)
	default:
		if typ.Qualifier != "" {
			g.line("%svar %s minigorpc.Value; %s, err = %s.Encode%s(%s); if err != nil { return }", indent, name, name, typ.Qualifier, g.importedTypeName(typ.Qualifier, typ.Name), expression)
			return
		}
		switch typ.Name {
		case "bool", "string":
			g.line("%s%s := minigorpc.Value{Type: %q, Data: %s}", indent, name, wireType, expression)
		case "uint8", "uint16", "uint32", "uint64":
			g.line("%s%s := minigorpc.Value{Type: %q, Data: uint64(%s)}", indent, name, wireType, expression)
		case "float32", "float64":
			g.line("%s%s := minigorpc.Value{Type: %q, Data: float64(%s)}", indent, name, wireType, expression)
		case "complex64", "complex128":
			g.line("%s%s := minigorpc.Value{Type: %q, Data: complex128(%s)}", indent, name, wireType, expression)
		default:
			if g.isMessage(typ.Name) {
				g.line("%svar %s minigorpc.Value; %s, err = Encode%s(%s); if err != nil { return }", indent, name, name, g.typeName(typ.Name), expression)
			} else {
				g.line("%s%s := minigorpc.Value{Type: %q, Data: int64(%s)}", indent, name, wireType, expression)
			}
		}
	}
}

func (g *generator) decodeValue(name, expression string, typ mrpc.Type, indent string) {
	if g.isResourceType(typ) {
		g.err = fmt.Errorf("resource %s requires a call owner", typ.String())
		return
	}
	wireType := g.wireType(typ)
	sourceType := g.goType(typ, false)
	switch typ.Kind {
	case mrpc.TypeSlice:
		if typ.Elem.Kind == mrpc.TypeName && typ.Elem.Qualifier == "" && typ.Elem.Name == "uint8" {
			g.line("%svar %s []uint8", indent, name)
			g.line("%sif %s.Type != %q { err = minigorpc.StatusError{Code: minigorpc.CodeProtocol, Message: \"invalid []uint8 value\"}; return }", indent, expression, wireType)
			g.line("%sif %s.Data != nil { raw, ok := %s.Data.([]byte); if !ok { err = minigorpc.StatusError{Code: minigorpc.CodeProtocol, Message: \"invalid []uint8 value\"}; return }; %s = append([]byte{}, raw...) }", indent, expression, expression, name)
			return
		}
		g.line("%svar %s %s", indent, name, sourceType)
		g.line("%sif %s.Type != %q { err = minigorpc.StatusError{Code: minigorpc.CodeProtocol, Message: \"invalid slice value\"}; return }", indent, expression, wireType)
		g.line("%sif %s.Data != nil {", indent, expression)
		g.line("%s\titems, ok := %s.Data.([]minigorpc.Value); if !ok { err = minigorpc.StatusError{Code: minigorpc.CodeProtocol, Message: \"invalid slice value\"}; return }", indent, expression)
		g.line("%s\t%s = make(%s, 0, len(items))", indent, name, sourceType)
		g.line("%s\tfor _, item := range items {", indent)
		g.decodeValue("decodedItem", "item", *typ.Elem, indent+"\t\t")
		g.line("%s\t\t%s = append(%s, decodedItem)", indent, name, name)
		g.line("%s\t}", indent)
		g.line("%s}", indent)
	case mrpc.TypeMap:
		g.line("%svar %s %s", indent, name, sourceType)
		g.line("%sif %s.Type != %q { err = minigorpc.StatusError{Code: minigorpc.CodeProtocol, Message: \"invalid map value\"}; return }", indent, expression, wireType)
		g.line("%sif %s.Data != nil {", indent, expression)
		g.line("%s\tentries, ok := %s.Data.([]minigorpc.MapEntry); if !ok { err = minigorpc.StatusError{Code: minigorpc.CodeProtocol, Message: \"invalid map value\"}; return }", indent, expression)
		g.line("%s\t%s = make(%s, len(entries))", indent, name, sourceType)
		g.line("%s\tfor _, entry := range entries {", indent)
		g.decodeValue("decodedKey", "entry.Key", *typ.Key, indent+"\t\t")
		g.decodeValue("decodedItem", "entry.Value", *typ.Elem, indent+"\t\t")
		g.line("%s\t\t%s[decodedKey] = decodedItem", indent, name)
		g.line("%s\t}", indent)
		g.line("%s}", indent)
	case mrpc.TypeOptional:
		g.line("%svar %s %s", indent, name, sourceType)
		g.line("%sif %s.Type != %q { err = minigorpc.StatusError{Code: minigorpc.CodeProtocol, Message: \"invalid optional value\"}; return }", indent, expression, wireType)
		g.line("%sif %s.Data != nil { raw, ok := %s.Data.(minigorpc.Value); if !ok { err = minigorpc.StatusError{Code: minigorpc.CodeProtocol, Message: \"invalid optional value\"}; return };", indent, expression, expression)
		g.decodeValue("decodedItem", "raw", *typ.Elem, indent+"\t")
		g.line("%s\t%s = &decodedItem", indent, name)
		g.line("%s}", indent)
	default:
		if typ.Qualifier != "" {
			g.line("%svar %s %s; %s, err = %s.Decode%s(%s); if err != nil { return }", indent, name, sourceType, name, typ.Qualifier, g.importedTypeName(typ.Qualifier, typ.Name), expression)
			return
		}
		if g.isMessage(typ.Name) {
			g.line("%svar %s %s; %s, err = Decode%s(%s); if err != nil { return }", indent, name, sourceType, name, g.typeName(typ.Name), expression)
			return
		}

		dataType := "int64"
		switch typ.Name {
		case "bool":
			dataType = "bool"
		case "string":
			dataType = "string"
		case "uint8", "uint16", "uint32", "uint64":
			dataType = "uint64"
		case "float32", "float64":
			dataType = "float64"
		case "complex64", "complex128":
			dataType = "complex128"
		}
		g.line("%sraw%s, ok := %s.Data.(%s); if %s.Type != %q || !ok { err = minigorpc.StatusError{Code: minigorpc.CodeProtocol, Message: \"invalid %s value\"}; return }", indent, name, expression, dataType, expression, wireType, typ.Name)
		g.line("%s%s := %s(raw%s)", indent, name, sourceType, name)
		if dataType == "int64" || dataType == "uint64" {
			g.line("%sif %s(%s) != raw%s { err = minigorpc.StatusError{Code: minigorpc.CodeProtocol, Message: \"numeric overflow\"}; return }", indent, dataType, name, name)
		} else if typ.Name == "float32" {
			g.line("%sif float64(%s) != raw%s { err = minigorpc.StatusError{Code: minigorpc.CodeProtocol, Message: \"numeric overflow\"}; return }", indent, name, name)
		} else if typ.Name == "complex64" {
			g.line("%sif complex128(%s) != raw%s { err = minigorpc.StatusError{Code: minigorpc.CodeProtocol, Message: \"numeric overflow\"}; return }", indent, name, name)
		}
	}
}

func (g *generator) typeName(name string) string { return g.prefix + exported(name) }

func (g *generator) importedTypeName(alias, name string) string {
	for _, file := range g.catalog.Files {
		for _, imported := range file.Imports {
			if imported.Alias == alias {
				return g.catalog.Dependencies[imported.Path].Options["go_prefix"] + exported(name)
			}
		}
	}
	return exported(name)
}

func (g *generator) isMessage(name string) bool {
	for _, file := range g.catalog.Files {
		for _, item := range file.Messages {
			if item.Name == name {
				return true
			}
		}
	}
	return false
}

func (g *generator) isResource(name string) bool {
	for _, file := range g.catalog.Files {
		for _, item := range file.Resources {
			if item.Name == name {
				return true
			}
		}
	}
	return false
}

func (g *generator) isResourceType(typ mrpc.Type) bool {
	resolved, err := g.catalog.ResolveType(typ)
	return err == nil && resolved.Kind == "resource"
}

func (g *generator) resourceFunction(typ mrpc.Type, prefix, suffix string) string {
	if typ.Qualifier != "" {
		return typ.Qualifier + "." + prefix + g.importedTypeName(typ.Qualifier, typ.Name) + suffix
	}
	return prefix + g.typeName(typ.Name) + suffix
}
